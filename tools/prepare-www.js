// tools/prepare-www.js — copy the website files into www/ for Capacitor.
//
// The repo root IS the website (GitHub Pages serves it directly), but
// Capacitor wants a clean webDir without node_modules, .git, tests, etc.
// This script copies exactly the files the app needs into www/.
//
// Run:  node tools/prepare-www.js
// Then: npx cap sync   (copies www/ into the android project)
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const WWW = path.join(ROOT, "www");

const FILES = [
  "index.html",
  "auth-callback.html",
  "styles.css",
  "rb-build.js",
  "config.js",
  "notify.js",
  "auth.js",
  "store.js",
  "qbooks.js",
  "qbooks-ui.js",
  "push.js",
  "rtc.js",
  "app.js",
  "sw.js",
  "manifest.webmanifest",
  "terms.html",
  "privacy.html",
  "vendor/supabase.js",
  "icons/icon-192.png",
  "icons/icon-512.png",
  "icons/maskable-512.png",
  "icons/apple-touch-icon.png"
];

fs.rmSync(WWW, { recursive: true, force: true });
fs.mkdirSync(WWW, { recursive: true });

let copied = 0;
for (const rel of FILES) {
  const src = path.join(ROOT, rel);
  if (!fs.existsSync(src)) {
    console.warn("  (missing, skipped) " + rel);
    continue;
  }
  const dest = path.join(WWW, rel);
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.copyFileSync(src, dest);
  copied++;
  console.log("  " + rel);
}

// ---------------------------------------------------------------------------
// Firebase stamp.
//
// The @capacitor/push-notifications plugin calls
// FirebaseMessaging.getInstance() on the Android main thread. If the APK was
// built WITHOUT android/app/google-services.json, Firebase is not initialized
// and that call throws — which kills the app the moment a person signs in.
//
// The build decides once, here, whether Firebase is part of this APK, and
// writes the answer into www/rb-build.js. push.js checks it before ever
// touching the push plugin, so a Firebase-less APK can never crash.
const googleServices = path.join(ROOT, "android", "app", "google-services.json");
const hasFirebase = fs.existsSync(googleServices);
let firebaseJson = "";
if (hasFirebase) {
  // Only the PUBLIC config (project id, app id, api key, sender id) is copied.
  // These are safe to ship: they are already inside every installed APK.
  try {
    const raw = JSON.parse(fs.readFileSync(googleServices, "utf8"));
    const project = raw.project_info || {};
    const client = (raw.client || [])[0] || {};
    const appId = (client.client_info || {}).mobilesdk_app_id || "";
    const publicConfig = {
      projectId: project.project_id || "",
      gcmSenderId: (client.client_info || {}).project_id || "",
      applicationId: appId,
      apiKey: ((client.api_key || [])[0] || {}).current_key || "",
      storageBucket: project.storage_bucket || "",
      appId: appId,
      messagingSenderId: (client.client_info || {}).project_id || ""
    };
    firebaseJson = JSON.stringify(publicConfig);
  } catch (e) {
    console.warn("  (google-services.json is not valid JSON — Firebase stays off)");
  }
}
const firebaseOn = hasFirebase && !!firebaseJson;
const stamp = `// rb-build.js — generated by tools/prepare-www.js. Do not edit by hand.
// Tells the app what this APK actually contains.
window.RB_BUILD = ${JSON.stringify({ firebase: firebaseOn, builtAt: new Date().toISOString() }, null, 2)};
window.RB_FIREBASE = ${firebaseOn};
window.RB_FIREBASE_CONFIG = ${firebaseJson || "null"};
`;
fs.writeFileSync(path.join(WWW, "rb-build.js"), stamp);
console.log(`  rb-build.js  (Firebase ${firebaseOn ? "ON" : "OFF — push registration skipped"})`);

console.log(`www/ ready — ${copied} files copied.`);
